const STOPWORDS = new Set([
  "how", "do", "i", "a", "an", "the", "to", "my", "for", "of", "in", "on", "can",
  "what", "when", "where", "is", "it", "me", "get", "help", "with", "and", "or", "new", "just",
]);

window.matchAnswer = function matchAnswer(query) {
  const tokens = query
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, " ")
    .split(/\s+/)
    .filter((t) => t && !STOPWORDS.has(t));
  if (!tokens.length) return null;

  let best = null;
  let bestScore = 0;
  for (const entry of window.SG_ANSWERS) {
    let score = 0;
    for (const t of tokens) {
      for (const k of entry.keywords) {
        if (t === k) score += 3;
        else if (t.length >= 3 && (k.startsWith(t) || t.startsWith(k))) score += 1;
      }
    }
    if (score > bestScore) {
      bestScore = score;
      best = entry;
    }
  }
  return bestScore >= 2 ? best : null;
};
